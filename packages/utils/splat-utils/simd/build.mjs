import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const wasm = execFileSync(
  process.env.CLANG || 'clang',
  [
    '--target=wasm32',
    '-msimd128',
    '-mbulk-memory',
    '-O3',
    '-ffp-contract=off',
    '-nostdlib',
    '-Wl,--no-entry',
    '-Wl,--strip-all',
    '-Wl,--export-memory',
    '-Wl,--export=__heap_base',
    '-Wl,--export=resetBuckets',
    '-Wl,--export=projectChunk',
    '-Wl,--export=writeOrder',
    'sort.c',
    '-o',
    '-',
  ],
  { cwd: import.meta.dirname, stdio: ['ignore', 'pipe', 'inherit'] },
);

// Embed the same binary for module workers and worker-loader's inline workers.
writeFileSync(
  new URL('./sort.wasm.js', import.meta.url),
  `// Generated by build.mjs.
const binary = globalThis.atob(
    '${wasm.toString('base64')}',
);
const bytes = new Uint8Array(binary.length);
for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
}
export default bytes.buffer;
`,
);
writeFileSync(
  new URL('./sort.wasm.d.ts', import.meta.url),
  'declare const buffer: ArrayBuffer;\nexport default buffer;\n',
);
